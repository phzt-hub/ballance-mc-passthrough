#!/usr/bin/env python3
"""Bakes the settings-panel font atlas.

The Ballance port draws its own UI from 2D sprites and the engine ships no
usable font asset for a hand-made overlay, so the panel carries its own tiny
bitmap font. This script rasterises printable ASCII (0x20..0x7F) from a system
DejaVu Sans Mono into a 16x6 grid of 8x12 cells, keeps the coverage as 8-bit
alpha, and writes it into a C++ header as base64 -- the panel decodes it into a
CKTexture at startup. Keeping the atlas generated (not hand-drawn) means the
glyphs are a real font's, and re-running this script is all it takes to change
size or typeface.

    python3 tools/panel/make-font-atlas.py [--size 10] [--out <header>]
"""
import argparse
import base64
import os
import subprocess

from PIL import Image, ImageDraw, ImageFont

CELL_W, CELL_H = 8, 12
COLUMNS, ROWS = 16, 6
FIRST, LAST = 0x20, 0x7F

DEFAULT_FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
DEFAULT_OUT = os.path.join(
    os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))),
    "..", "Ballanced", "Source", "Player", "src", "MinecraftFontAtlas.h")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--size", type=int, default=10)
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--out", default=os.path.normpath(DEFAULT_OUT))
    args = ap.parse_args()

    font = ImageFont.truetype(args.font, args.size)
    width, height = CELL_W * COLUMNS, CELL_H * ROWS
    atlas = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(atlas)
    baseline = CELL_H - 2
    for code in range(FIRST, LAST):
        index = code - FIRST
        cx = (index % COLUMNS) * CELL_W
        cy = (index // COLUMNS) * CELL_H
        draw.text((cx, cy + baseline), chr(code), fill=255, font=font, anchor="ls")

    blob = atlas.tobytes()
    packed = base64.b64encode(blob).decode("ascii")
    lines = [packed[i:i + 96] for i in range(0, len(packed), 96)]
    with open(args.out, "w") as out:
        out.write("// Generated by tools/panel/make-font-atlas.py -- do not edit.\n")
        out.write("//\n")
        out.write("// %d glyphs (0x%02X..0x%02X) in a %dx%d grid of %dx%d cells, 8-bit\n"
                  % (LAST - FIRST, FIRST, LAST - 1, COLUMNS, ROWS, CELL_W, CELL_H))
        out.write("// coverage, base64. Cell (code - 0x20) lives at column/row of the grid.\n")
        out.write("#ifndef PLAYER_MINECRAFTFONTATLAS_H\n")
        out.write("#define PLAYER_MINECRAFTFONTATLAS_H\n\n")
        out.write("namespace mc_font {\n\n")
        out.write("constexpr int kCellWidth = %d;\n" % CELL_W)
        out.write("constexpr int kCellHeight = %d;\n" % CELL_H)
        out.write("constexpr int kColumns = %d;\n" % COLUMNS)
        out.write("constexpr int kRows = %d;\n" % ROWS)
        out.write("constexpr int kFirstCode = 0x%02X;\n" % FIRST)
        out.write("constexpr int kGlyphCount = %d;\n\n" % (LAST - FIRST))
        out.write("constexpr const char *kAtlasBase64 =\n")
        for line in lines:
            out.write('    "%s"\n' % line)
        out.write("    ;\n\n} // namespace mc_font\n\n#endif\n")
    print("wrote %s (%d bytes atlas, %d base64)" % (args.out, len(blob), len(packed)))


if __name__ == "__main__":
    main()
